"""Render docs/production_readiness.md from a readiness scorecard JSON.

    trend-agent system readiness --write docs/benchmarks/phase8_readiness.json
    python scripts/render_readiness.py docs/benchmarks/phase8_readiness.json

The document is generated from the measured scorecard so that the prose cannot drift
from the evidence; only the fixed explanation at the top is hand-written.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

HEADER = """# Production readiness

Generated by `scripts/render_readiness.py` from `{source}` (scorecard of {at}).
Re-generate after every deployment or evidence change; do not edit the tables by hand.

## How to read this

Each item is **PASS**, **FAIL**, **BLOCKED** (cannot pass for a reason outside the code: a
credential, an access grant, a legal review, a deployment that has not happened) or
**NOT_APPLICABLE**. BLOCKED is never counted as PASS. Scopes:

* `build`: the code base itself (tests, scans, artifacts, offline evaluation).
* `runtime`: needs a running deployment (scheduler, workers, data, backups, alerting,
  production configuration).
* `external`: needs third parties (search-interest access, policy review, labelled
  reality, a deployment target).

Release states:

| State | Meaning |
|---|---|
| NOT_READY | any build item fails |
| BLOCKED | any build item is blocked |
| STAGING_READY | every build item passes; runtime or external items do not |
| LIMITED_PRODUCTION_READY | build and runtime pass, a proxy provider is live and the \
compliance review passed; only search-interest access and real-world accuracy are blocked |
| PRODUCTION_READY | every item passes or is not applicable |
"""


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "docs/benchmarks/phase8_readiness.json"
    d = json.loads(src.read_text())
    out = [
        HEADER.format(
            source=src.relative_to(ROOT) if src.is_relative_to(ROOT) else src, at=d["generated_at"]
        )
    ]
    c = d["counts"]
    out.append(f"## Result: **{d['release_state']}**\n")
    out.append(
        f"PASS {c['PASS']} · FAIL {c['FAIL']} · BLOCKED {c['BLOCKED']} · "
        f"NOT_APPLICABLE {c['NOT_APPLICABLE']}\n"
    )
    for r in d["reasons"]:
        out.append(f"* {r}")
    m = d.get("operating_mode")
    if m:
        out.append(
            f"\nOperating mode at the time: **{m['mode']}** (base {m['base_mode']}); "
            f"direct YouTube Search surge claims "
            f"{'enabled' if m['direct_search_claims_enabled'] else '**disabled**'}."
        )
    for scope in ("build", "runtime", "external"):
        out.append(f"\n## {scope.capitalize()} items\n")
        out.append("| Item | Area | Status | Evidence | Action |")
        out.append("|---|---|---|---|---|")
        for i in d["items"]:
            if i["scope"] != scope:
                continue
            ev = i["evidence"].replace("|", "/").replace("\n", " ")
            out.append(
                f"| `{i['key']}` | {i['area']} | **{i['status']}** | {ev} | "
                f"{i.get('action', '').replace('|', '/')} |"
            )
    out.append(
        "\n## What would change the state\n\n"
        "* **STAGING_READY → LIMITED_PRODUCTION_READY:**\n"
        "  * deploy and record it;\n"
        "  * run a scheduler and workers;\n"
        "  * configure an alert channel;\n"
        "  * set production secrets;\n"
        "  * configure a YouTube API key and pass the smoke test;\n"
        "  * collect real data;\n"
        "  * run the restore drill on production;\n"
        "  * complete and record the YouTube API compliance review.\n"
        "* **LIMITED_PRODUCTION_READY → PRODUCTION_READY:**\n"
        "  * a legitimate DIRECT_YOUTUBE_SEARCH_INTEREST provider, live-verified;\n"
        "  * ≥ 30 labelled real surges;\n"
        "  * ≥ 50 labelled real gaps;\n"
        "  * ≥ 100 real forecast outcomes;\n"
        "  * evaluations on them meeting the floors in `live_data_readiness.md`.\n"
    )
    (ROOT / "docs/production_readiness.md").write_text("\n".join(out) + "\n")
    print(f"wrote docs/production_readiness.md ({d['release_state']})")


if __name__ == "__main__":
    main()
